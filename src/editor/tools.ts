/**
 * Название и подсказка для текущего инструмента. В разделе «Транспорт» нет
 * инструмента выбора объектов, поэтому там показывается подсказка раздела.
 */
export function toolInstruction(
  tool: EditorTool,
  mode: "edit" | "traffic",
): { name: string; hint: string } {
  if (mode === "traffic" && tool === "select")
    return {
      name: "Транспорт",
      hint: "Выберите слева: машина, остановка или маршрут автобуса. Машину или остановку можно выделить кликом.",
    };
  return editorTools.find((item) => item.id === tool)!;
}
